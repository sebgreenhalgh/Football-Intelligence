def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def require_stage() -> None:
    if not MANIFEST_PATH.is_file():
        pytest.skip("M5.5D.3A outputs are generated by the build command")


def cases() -> list[dict]:
    require_stage()
    return read_json(MANIFEST_PATH)["cases"]


