def test_repaired_package_has_twenty_seven_cases() -> None:
    assert len(cases()) == 27


def test_question_is_exact_and_target_is_not_numbered() -> None:
    for case in cases():
        assert (
            case["concise_question"]
            == "Does any numbered box cover the same visible person as the red highlighted target?"
        )
        assert case["visible_metadata"]["target_label"] == TARGET_LABEL
        target_layers = [
            row for row in case["visible_metadata"]["geometry_layers"] if row["layer"] == "TARGET_HIGHLIGHT"
        ]
        assert len(target_layers) == 1
        assert target_layers[0].get("anonymous_candidate_number") is None


def test_decision_taxonomy_is_exact() -> None:
    for case in cases():
        assert case["allowed_decisions"] == DECISION_VALUES


def test_duplicate_is_the_only_counterpart_required_decision() -> None:
    for case in cases():
        assert case["visible_metadata"]["counterpart_required_decisions"] == [DECISION_VALUES[0]]
        assert case["visible_metadata"]["counterpart_field"] == "duplicate_counterpart_number"


def test_numbered_candidates_are_contiguous_after_exclusion() -> None:
    for case in cases():
        numbers = [row["anonymous_candidate_number"] for row in case["competing_candidates"]]
        assert numbers == list(range(1, len(numbers) + 1))
        assert case["visible_metadata"]["candidate_count"] == len(numbers)


def test_numbered_candidates_are_other_same_frame_canonical_rows() -> None:
    for case in cases():
        frame = case["target_frame_sequence"]
        assert all(row["frame_sequence"] == frame for row in case["competing_candidates"])
        assert all(row["coordinate_space"] == "ORIGINAL_PANORAMA_PIXELS" for row in case["competing_candidates"])


def test_target_frame_is_native_2730_by_720() -> None:
    for case in cases():
        binding = case["visible_metadata"]["coordinate_binding"]
        assert binding["coordinate_space"] == "ORIGINAL_PANORAMA_PIXELS"
        assert binding["width"] == 2730
        assert binding["height"] == 720


def test_target_and_context_layers_are_visible_by_default() -> None:
    for case in cases():
        visibility = case["visible_metadata"]["layer_visibility"]
        assert visibility["TARGET_HIGHLIGHT"] is True
        assert visibility["CANONICAL_CONTEXT"] is True
        assert visibility["RAW_FRAME"] is True


def test_each_case_has_temporal_gif_and_frame_stepper() -> None:
    for case in cases():
        assets = case["evidence_assets"]
        assert sum(asset["asset_type"] == "animated_gif" for asset in assets) == 1
        assert sum(asset["asset_type"] == "image_sequence" for asset in assets) >= 3
        assert any(
            asset["asset_type"] == "image_sequence" and asset["metadata"].get("annotation_base") for asset in assets
        )


def test_each_numbered_candidate_has_exact_and_padded_crops() -> None:
    for case in cases():
        assets = {asset["asset_id"] for asset in case["evidence_assets"]}
        for number in range(1, case["visible_metadata"]["candidate_count"] + 1):
            assert f"candidate_{number:03d}_exact" in assets
            assert f"candidate_{number:03d}_padded" in assets


def test_target_has_exact_and_padded_crops() -> None:
    for case in cases():
        assets = {asset["asset_id"] for asset in case["evidence_assets"]}
        assert {"target_exact", "target_padded", "candidate_comparison_strip"} <= assets


